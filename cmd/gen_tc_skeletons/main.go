package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type tcRow struct {
	ID     string
	Kind   string
	Name   string
	Status string
	File   string
}

var tcID = regexp.MustCompile(`^TC-[A-Z]\d+-\d+$`)

func main() {
	root, _ := os.Getwd()
	docPath := filepath.Join(root, "docs", "TEST_CASES.md")
	outPath := filepath.Join(root, "tests", "tc_skeletons_test.go")

	f, err := os.Open(docPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to open document: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	var rows []tcRow
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		if !strings.HasPrefix(strings.TrimSpace(line), "|") {
			continue
		}

		parts := strings.Split(line, "|")
		if len(parts) < 4 {
			continue
		}
		trim := func(s string) string { return strings.TrimSpace(s) }
		id := trim(parts[1])
		if !tcID.MatchString(id) {
			continue
		}
		var r tcRow
		r.ID = id
		if len(parts) >= 3 {
			r.Kind = trim(parts[2])
		}
		if len(parts) >= 4 {
			r.Name = trim(parts[3])
		}
		if len(parts) >= 8 {
			r.Status = trim(parts[7])
		}
		if len(parts) >= 9 {
			r.File = trim(parts[8])
		}
		rows = append(rows, r)
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintf(os.Stderr, "failed to read document: %v\n", err)
		os.Exit(1)
	}

	var pending []tcRow
	for _, r := range rows {
		if strings.Contains(r.Status, "Pending") {
			pending = append(pending, r)
		}
	}

	var sb strings.Builder
	sb.WriteString("// Auto-generated by T01 skeleton generator (tests/tc_skeletons_test.go).\n")
	sb.WriteString("// Source: docs/TEST_CASES.md -> Test skeletons for pending cases.\n")
	sb.WriteString("// Re-generate with: `go run ./cmd/gen_tc_skeletons`.\n")
	sb.WriteString("package tests\n\n")
	sb.WriteString("import (\n\t\"testing\"\n)\n\n")

	for _, r := range pending {
		fn := "TestTC" + strings.ReplaceAll(r.ID[3:], "-", "_")
		sb.WriteString("// ")
		sb.WriteString(r.ID)
		sb.WriteString(" | Type: ")
		sb.WriteString(orDash(r.Kind))
		sb.WriteString(" | Name: ")
		sb.WriteString(orDash(r.Name))
		if r.File != "" && r.File != "—" && r.File != "-" {
			sb.WriteString(" | File: ")
			sb.WriteString(r.File)
		}
		sb.WriteString("\n")
		sb.WriteString("// Skeleton placeholder\n")
		sb.WriteString("func ")
		sb.WriteString(fn)
		sb.WriteString("(t *testing.T) {\n")
		sb.WriteString("\tt.Skip(\"T01 skeleton placeholder: ")
		sb.WriteString(r.ID)
		sb.WriteString("\")\n\t_ = t\n}\n\n")
	}

	if err := os.WriteFile(outPath, []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write file: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Generated: %s (%d pending skeletons, source %d TCs)\n", outPath, len(pending), len(rows))
}

func orDash(s string) string {
	if s == "" || s == "—" || s == "-" {
		return "-"
	}
	return s
}
